using System;
using System.IO;
using System.Linq;
using HideAndShoot.Player;
using UnityEditor;
using UnityEngine;

namespace HideAndShoot.EditorTools
{
    /// <summary>
    /// Build a persistent first-person Kyle RIGHT arm mesh. Never replace or
    /// delete original Kyle FBX or the previous two-arm FPSKyle_Arms_0 asset.
    /// </summary>
    [InitializeOnLoad]
    public static class FirstPersonRightArmInstaller
    {
        private const string Prefab="Assets/HideAndShoot/Prefabs/PlayerAvatar.prefab";
        private const string MeshPath="Assets/HideAndShoot/Animations/FPS_RightArm_0.asset";
        private const string AuditPath="Assets/HideAndShoot/QA/FPS_RIGHT_ARM_INSTALL_AUDIT.txt";

        static FirstPersonRightArmInstaller()=>EditorApplication.update+=TryInstall;

        private static void TryInstall()
        {
            if(EditorApplication.isPlayingOrWillChangePlaymode ||
               EditorApplication.isCompiling || EditorApplication.isUpdating)return;
            EditorApplication.update-=TryInstall;
            Install();
        }

        [MenuItem("Tools/HideAndShoot/Build RIGHT Arm Only FPS Mesh")]
        public static void Install()
        {
            if(EditorApplication.isPlayingOrWillChangePlaymode)return;
            if(AssetDatabase.LoadAssetAtPath<GameObject>(Prefab)==null)return;
            var player=PrefabUtility.LoadPrefabContents(Prefab);
            try
            {
                var visual=player.transform.Find(
                    "FPSRig_OWNER_ONLY/FPSArmsRig_TO_BUILD/FPS_KyleArmsSkinned");
                var animator=visual?.GetComponentInChildren<Animator>(true);
                if(visual==null || animator==null)
                {
                    Debug.LogError("[HideAndShoot/FPS] Right arm rig or Animator missing.");
                    return;
                }

                // If a valid single-right-arm mesh is already saved, do not
                // rewrite it on every domain reload (GUID stays stable).
                var persistent=AssetDatabase.LoadAssetAtPath<Mesh>(MeshPath);
                var skin=visual.GetComponentsInChildren<SkinnedMeshRenderer>(true)
                    .FirstOrDefault(s=>s.sharedMesh!=null);
                if(skin==null)
                {
                    Debug.LogError("[HideAndShoot/FPS] Skinned arm mesh missing.");
                    return;
                }

                if(persistent==null)
                {
                    int selected=FirstPersonRightArmMesh.Restrict(animator,visual);
                    if(selected<=0)
                    {
                        Debug.LogError("[HideAndShoot/FPS] Right-arm triangle extraction failed.");
                        return;
                    }
                    // Source FPSKyle_Arms_0 remains untouched. Persist only the
                    // newly cloned runtime Mesh generated by Restrict().
                    var rightMesh=skin.sharedMesh;
                    rightMesh.name="FPS_RightArm_0";
                    Directory.CreateDirectory(Path.GetDirectoryName(MeshPath));
                    AssetDatabase.CreateAsset(rightMesh,MeshPath);
                    persistent=rightMesh;
                }

                skin.sharedMesh=persistent;
                skin.enabled=true;
                // The world-handgun copy inside RobotKyleWorldVisual must stay
                // off; the owner-specific PistolViewModel renders separately.
                foreach(var renderer in visual.GetComponentsInChildren<MeshRenderer>(true))
                    if(renderer.name=="Pistol_ProvisionalCandidate")renderer.enabled=false;
                var layer=LayerMask.NameToLayer("FPSViewModel");
                if(layer>=0)
                    foreach(var child in visual.GetComponentsInChildren<Transform>(true))
                        child.gameObject.layer=layer;
                PrefabUtility.SaveAsPrefabAsset(player,Prefab);
                var message="Right arm triangles="+persistent.triangles.Length/3+
                            ", sourceOriginalIntact="+(persistent.name=="FPS_RightArm_0")+
                            ", prefab="+Prefab+", mesh="+MeshPath;
                File.WriteAllText(AuditPath,message+Environment.NewLine);
                Debug.Log("[HideAndShoot/FPS] Saved persistent "+message);
            }
            finally{PrefabUtility.UnloadPrefabContents(player);}
        }
    }
}
